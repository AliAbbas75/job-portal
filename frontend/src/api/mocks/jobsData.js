// Sample jobs for mock mode only. Dates are relative to page load so the demo never goes stale.

const HOUR = 60 * 60 * 1000;
const DAY = 24 * HOUR;
const now = Date.now();
const at = (offsetMs) => new Date(now + offsetMs).toISOString();

const standardDocs = ['cnic_copy', 'photo', 'domicile_certificate', 'character_certificate'];

function job(fields) {
  const {
    publishedAgo,
    closesIn,
    minLevel,
    minMarks = null,
    experienceYears = 0,
    ageMin = 18,
    ageMax = 30,
    domicile = [],
    documents,
    ...rest
  } = fields;
  return {
    status: closesIn < 0 ? 'closed' : 'published',
    publishedAt: at(-publishedAgo),
    openingDate: at(-publishedAgo),
    closingDate: at(closesIn * DAY),
    fee: 0,
    requirements: {
      minQualification: minLevel,
      minMarksPercent: minMarks,
      experienceYears,
      ageMin,
      ageMax,
      domicileProvinces: domicile,
      documents: [...standardDocs, ...documents],
    },
    ...rest,
  };
}

